def edition_plan(ids, docs, limit, seed, cases, order):
    if seed:
        yield from plan(ids, docs, limit, True, cases, order)
        return
    versions = [0, 0]
    notes = {
        label: (label, ch, action, q, ver)
        for label, ch, action, q, ver in plan(ids, docs, 24, False, cases, order)
        if action == "note"
    }
    for i, b in enumerate(order[:limit], 1):
        if i in CHANGES:
            side, revision = CHANGES[i]
            versions[side] = revision
            yield notes[f"rev{i}"]
        ch = ids[b]
        latest = i % 2 == 1
        phrase = cases[ch][int(i % 6 not in (1, 2))]
        edition = (
            ("按排演工作稿最后一次更正", "只取工作稿现在生效的版本")
            if latest
            else ("切回未改动的小说原文", "按小说原始正文")
        )[(i // 2) % 2]
        follow = ("接着刚才的", "换回这条线", "再核一下", "还是刚才那件事")[i % 4]
        question = f"{follow}，第{ch}章。{edition}，{phrase}？"
        if not latest and i % 6 != 2:
            question += DETAIL[ch] + "？"
        yield f"q{i}", ch, "ask", question, versions[b] if latest else None


def grade(answer, ch, version, cases):
    original, revisions = cases[ch][2:4]
    groups = original if version is None else tuple((v,) for v in revisions[version])
    old = [x for rev in revisions[:version] for x in rev] if version is not None else []
    if version is not None:
        old.extend(x for g in original for x in g)
    return all(any(v in answer for v in group) for group in groups), any(v in answer for v in old)


